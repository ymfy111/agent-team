#!/usr/bin/env node
/**
 * Archive completed WorkItem task details before cleaning active docs/runtime space.
 *
 * Usage:
 *   node docs/archive-completed-workitems.mjs --workitem TF-FACTORY-UI-ARCH --dry-run
 *   node docs/archive-completed-workitems.mjs --workitem TF-FACTORY-UI-ARCH --archive --archive-root /mnt/data/agent-team-archives
 *   node docs/archive-completed-workitems.mjs --workitem TF-FACTORY-UI-ARCH --clean --manifest /path/to/archive-manifest.json
 *
 * Design rules:
 * - archive before clean;
 * - never delete WorkItem ledger, closeout report, project-memory, or docs navigation;
 * - only completed/PASS task detail files are eligible;
 * - clean requires an archive manifest generated by --archive.
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const scriptPath = new URL(import.meta.url).pathname;
const docsDir = path.dirname(scriptPath);
const repoRoot = path.resolve(docsDir, '..');

function parseArgs(argv) {
  const args = { mode: null, archiveRoot: '/mnt/data/agent-team-archives' };
  for (let i = 2; i < argv.length; i += 1) {
    const item = argv[i];
    if (item === '--dry-run') args.mode = 'dry-run';
    else if (item === '--archive') args.mode = 'archive';
    else if (item === '--clean') args.mode = 'clean';
    else if (item === '--workitem') args.workitem = argv[++i];
    else if (item === '--archive-root') args.archiveRoot = argv[++i];
    else if (item === '--manifest') args.manifest = argv[++i];
    else if (item === '--help' || item === '-h') args.help = true;
    else throw new Error(`Unknown argument: ${item}`);
  }
  return args;
}

function usage() {
  return `Usage:\n  node docs/archive-completed-workitems.mjs --workitem <WorkItemId> --dry-run\n  node docs/archive-completed-workitems.mjs --workitem <WorkItemId> --archive [--archive-root <dir>]\n  node docs/archive-completed-workitems.mjs --workitem <WorkItemId> --clean --manifest <archive-manifest.json>`;
}

function exists(p) {
  return fs.existsSync(p);
}

function listFiles(dir) {
  if (!exists(dir)) return [];
  const result = [];
  const walk = (current) => {
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.isFile()) result.push(full);
    }
  };
  walk(dir);
  return result;
}

function rel(abs) {
  return path.relative(repoRoot, abs).replaceAll(path.sep, '/');
}

function readText(p) {
  return fs.readFileSync(p, 'utf8');
}

function isCompletedTaskFile(file) {
  const text = readText(file);
  return /Status:\s*PASS/i.test(text)
    || /状态[：:]\s*PASS/i.test(text)
    || /^-\s*状态[：:]\s*PASS/im.test(text);
}

function getTaskIdFromTaskFile(file) {
  const base = path.basename(file, '.md');
  return base.replace(/^TASK_/, '');
}

function taskReportTokens(workitemId, taskId) {
  const tokens = new Set([taskId]);
  const shortWorkitem = workitemId.replace(/^TF-/, '');
  const suffix = taskId.startsWith(`${workitemId}-`) ? taskId.slice(workitemId.length + 1) : '';
  if (suffix) {
    tokens.add(`${shortWorkitem}-${suffix}`);
    tokens.add(`ARCH-${suffix}`);
    tokens.add(`arch-${suffix}`);
  }
  return [...tokens];
}

function collectWorkItemFiles(workitemId) {
  const workitemFile = path.join(repoRoot, 'docs', 'workitems', `${workitemId}.md`);
  if (!exists(workitemFile)) {
    throw new Error(`WorkItem file not found: ${rel(workitemFile)}`);
  }

  const tasksDir = path.join(repoRoot, 'docs', 'tasks', workitemId);
  const allTaskFiles = listFiles(tasksDir).filter((f) => f.endsWith('.md'));
  const completedTaskFiles = allTaskFiles.filter(isCompletedTaskFile);
  const completedTaskIds = completedTaskFiles.map(getTaskIdFromTaskFile);
  const tokens = completedTaskIds.flatMap((taskId) => taskReportTokens(workitemId, taskId));

  const reportsDir = path.join(repoRoot, 'docs', 'reports');
  const reportFiles = listFiles(reportsDir)
    .filter((f) => f.endsWith('.md'))
    .filter((f) => {
      const name = path.basename(f);
      // Keep closeout/summary reports in active project; archive QA/task-level reports.
      if (!/^QA-/i.test(name)) return false;
      return tokens.some((token) => name.includes(token));
    });

  const execDir = path.join(repoRoot, '.runtime', 'exec', workitemId);
  const execFiles = completedTaskIds
    .map((taskId) => path.join(execDir, `${taskId}.json`))
    .filter(exists);

  const shortWorkitem = workitemId.replace(/^TF-/, '');
  const batchDir = path.join(repoRoot, '.runtime', 'batches');
  const batchFiles = listFiles(batchDir)
    .filter((f) => path.basename(f).startsWith(`TB-${shortWorkitem}-`) && f.endsWith('.json'));

  const qaDir = path.join(repoRoot, 'apps', 'web', 'qa');
  const qaFiles = listFiles(qaDir).filter((f) => {
    const name = rel(f);
    return tokens.some((token) => name.includes(token) || name.includes(token.toLowerCase()))
      || /ui-arch-(0[7-9]|1[0-3])/.test(name)
      || /arch-(0[7-9]|1[0-3])/.test(name);
  });

  const preserveFiles = [
    rel(workitemFile),
    'docs/project-memory.md',
    'docs/doc-nav.md',
    'docs/reports/RPT-FRONTEND-UI-ARCH-13-CLOSEOUT.md',
  ].filter((p) => exists(path.join(repoRoot, p)));

  const archiveCandidates = [...new Set([
    ...completedTaskFiles,
    ...reportFiles,
    ...execFiles,
    ...batchFiles,
    ...qaFiles,
  ].map(rel))].sort();

  return {
    workitemId,
    workitemFile: rel(workitemFile),
    completedTaskIds,
    archiveCandidates,
    preserveFiles,
    stats: {
      completedTasks: completedTaskIds.length,
      taskFiles: completedTaskFiles.length,
      reportFiles: reportFiles.length,
      execFiles: execFiles.length,
      batchFiles: batchFiles.length,
      qaFiles: qaFiles.length,
      totalArchiveCandidates: archiveCandidates.length,
    },
  };
}

function printPlan(plan) {
  console.log(`Archive plan for ${plan.workitemId}`);
  console.log('');
  console.log('Stats:');
  for (const [key, value] of Object.entries(plan.stats)) console.log(`  - ${key}: ${value}`);
  console.log('');
  console.log('Completed Tasks:');
  for (const taskId of plan.completedTaskIds) console.log(`  - ${taskId}`);
  console.log('');
  console.log('Preserved in active project:');
  for (const file of plan.preserveFiles) console.log(`  - ${file}`);
  console.log('');
  console.log('Archive candidates:');
  for (const file of plan.archiveCandidates) console.log(`  - ${file}`);
}

function copyFileInto(root, relPath) {
  const src = path.join(repoRoot, relPath);
  const dst = path.join(root, relPath);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(src, dst);
}

function createArchive(plan, archiveRoot) {
  const archiveDir = path.join(archiveRoot, plan.workitemId);
  fs.mkdirSync(archiveDir, { recursive: true });
  const runId = `${plan.workitemId}-completed-archive`;
  const stagingDir = path.join(archiveDir, runId);
  fs.rmSync(stagingDir, { recursive: true, force: true });
  fs.mkdirSync(stagingDir, { recursive: true });

  for (const file of plan.archiveCandidates) copyFileInto(stagingDir, file);

  const manifest = {
    archiveType: 'completed-workitem-details',
    workitemId: plan.workitemId,
    createdAt: new Date().toISOString(),
    repoRoot,
    stagingDir,
    cleanAllowed: true,
    rule: 'Archive completed task details only; keep WorkItem ledger, closeout report, project-memory, navigation, and unfinished tasks in active project.',
    completedTaskIds: plan.completedTaskIds,
    preservedInActiveProject: plan.preserveFiles,
    archivedFiles: plan.archiveCandidates,
    stats: plan.stats,
  };
  const manifestPath = path.join(stagingDir, 'ARCHIVE-MANIFEST.json');
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2), 'utf8');
  fs.writeFileSync(path.join(stagingDir, 'ARCHIVE-MANIFEST.md'), renderManifestMarkdown(manifest), 'utf8');

  const zipPath = path.join(archiveDir, `${runId}.zip`);
  fs.rmSync(zipPath, { force: true });
  execFileSync('zip', ['-qr', zipPath, '.'], { cwd: stagingDir });

  console.log(`Archive created: ${zipPath}`);
  console.log(`Manifest: ${manifestPath}`);
  console.log(`Archived files: ${plan.archiveCandidates.length}`);
  return { zipPath, manifestPath, stagingDir };
}

function renderManifestMarkdown(manifest) {
  return `# ${manifest.workitemId} Completed Task Archive\n\n` +
    `- CreatedAt: ${manifest.createdAt}\n` +
    `- WorkItem: ${manifest.workitemId}\n` +
    `- Archived files: ${manifest.archivedFiles.length}\n` +
    `- Completed tasks: ${manifest.completedTaskIds.length}\n\n` +
    `## Preserved in active project\n\n` +
    manifest.preservedInActiveProject.map((f) => `- ${f}`).join('\n') +
    `\n\n## Completed tasks\n\n` +
    manifest.completedTaskIds.map((f) => `- ${f}`).join('\n') +
    `\n\n## Archived files\n\n` +
    manifest.archivedFiles.map((f) => `- ${f}`).join('\n') + '\n';
}

function cleanFromManifest(manifestPath) {
  if (!manifestPath || !exists(manifestPath)) throw new Error('clean requires --manifest <archive-manifest.json>');
  const manifest = JSON.parse(readText(manifestPath));
  if (!manifest.cleanAllowed || !Array.isArray(manifest.archivedFiles)) {
    throw new Error('manifest is not cleanable or missing archivedFiles');
  }
  const protectedPrefixes = [
    'docs/workitems/',
    'docs/project-memory.md',
    'docs/doc-nav.md',
    'docs/reports/RPT-',
    'apps/', // protect app source; qa files under apps/web/qa are allowed below
  ];
  const cleaned = [];
  for (const file of manifest.archivedFiles) {
    const isQa = file.startsWith('apps/web/qa/');
    const protectedFile = protectedPrefixes.some((prefix) => file.startsWith(prefix)) && !isQa;
    if (protectedFile) continue;
    const abs = path.join(repoRoot, file);
    if (exists(abs)) {
      fs.rmSync(abs, { force: true });
      cleaned.push(file);
    }
  }
  console.log(`Cleaned files: ${cleaned.length}`);
  for (const file of cleaned) console.log(`  - ${file}`);
}

function main() {
  const args = parseArgs(process.argv);
  if (args.help || !args.mode || !args.workitem) {
    console.log(usage());
    process.exit(args.help ? 0 : 1);
  }
  const plan = collectWorkItemFiles(args.workitem);
  if (args.mode === 'dry-run') {
    printPlan(plan);
  } else if (args.mode === 'archive') {
    printPlan(plan);
    console.log('');
    createArchive(plan, args.archiveRoot);
  } else if (args.mode === 'clean') {
    cleanFromManifest(args.manifest);
  } else {
    throw new Error(`Unsupported mode: ${args.mode}`);
  }
}

try {
  main();
} catch (error) {
  console.error(`ERROR: ${error.message}`);
  process.exit(1);
}
